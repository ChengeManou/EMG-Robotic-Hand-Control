"""
export_rf_weights.py

Exports every tree in a fitted RandomForestClassifier into a single
flat binary file of fixed-size node records, plus a small metadata
module rf_weights.py -- same binary-not-source-literals approach as
export_test_windows.py, because RF node counts can run into the
hundreds of thousands (a literal Python list would be unusable).

Each node record (RECORD_FMT, little-endian):
    child_left  : int32   (-1 if this node is a leaf)
    child_right : int32   (-1 if this node is a leaf)
    feature     : int32   (index into the 16-dim TD feature vector;
                            meaningless at a leaf)
    threshold   : float32 (meaningless at a leaf)
    proba[0..N_CLASSES-1] : float32 each
                            (this node's class distribution, normalized
                            to sum to 1 -- only meaningful/used at leaves,
                            but stored for every node for simple flat
                            indexing)

child_left/child_right are GLOBAL indices into this same flat file
(each tree's originally-tree-relative indices are offset by that
tree's starting position at export time), so traversal never needs to
know which tree it's in beyond the starting node.

Writes:
    rf_nodes.bin   - packed binary, TOTAL_NODES records of RECORD_SIZE
                     bytes each
    rf_weights.py  - metadata: N_TREES, N_CLASSES, N_FEATURES,
                     CLASS_IDS, LABELS, TREE_STARTS (global root index
                     per tree), TOTAL_NODES, RECORD_SIZE, RECORD_FMT,
                     BIN_PATH

Usage:
    python export_rf_weights.py
"""

import struct
import joblib
import numpy as np

MODEL_PATH = "rf_model.joblib"
TEST_WINDOWS_PATH = "test_windows.npz"
BIN_OUT_PATH = "rf_nodes.bin"
META_OUT_PATH = "rf_weights.py"


def main():
    rf = joblib.load(MODEL_PATH)

    tw = np.load(TEST_WINDOWS_PATH, allow_pickle=True)
    label_map = dict(zip(tw["label_map_keys"].tolist(), tw["label_map_values"].tolist()))

    class_ids = rf.classes_
    n_classes = len(class_ids)
    n_features = rf.n_features_in_

    if n_classes != len(label_map):
        raise RuntimeError(
            f"rf.classes_ has {n_classes} entries but label_map has "
            f"{len(label_map)} -- a class was dropped upstream."
        )
    labels = [label_map[c] for c in class_ids]

    record_fmt = "<iiif" + "f" * n_classes
    record_size = struct.calcsize(record_fmt)

    tree_starts = []
    all_records = []  # list of packed bytes, appended in global order

    for est in rf.estimators_:
        t = est.tree_
        offset = len(all_records)  # this tree's global start index
        tree_starts.append(offset)

        n_nodes = t.node_count
        children_left = t.children_left
        children_right = t.children_right
        feature = t.feature
        threshold = t.threshold
        # value shape: (n_nodes, 1, n_classes) for single-output classification
        value = t.value[:, 0, :]
        row_sums = value.sum(axis=1, keepdims=True)
        row_sums[row_sums == 0] = 1.0  # guard, shouldn't happen but be safe
        proba = (value / row_sums).astype(np.float32)

        for node_id in range(n_nodes):
            cl = children_left[node_id]
            cr = children_right[node_id]
            is_leaf = cl == -1  # sklearn's TREE_LEAF sentinel
            global_cl = -1 if is_leaf else offset + int(cl)
            global_cr = -1 if is_leaf else offset + int(cr)
            feat = -1 if is_leaf else int(feature[node_id])
            thresh = 0.0 if is_leaf else float(threshold[node_id])
            rec = struct.pack(
                record_fmt,
                global_cl, global_cr, feat, thresh,
                *[float(v) for v in proba[node_id]]
            )
            all_records.append(rec)

    total_nodes = len(all_records)
    print(f"Trees: {len(rf.estimators_)}")
    print(f"Total nodes: {total_nodes}")
    print(f"Record size: {record_size} bytes")

    with open(BIN_OUT_PATH, "wb") as f:
        for rec in all_records:
            f.write(rec)

    n_bytes = total_nodes * record_size
    print(f"Wrote {BIN_OUT_PATH}: {n_bytes/1024:.1f} KB ({n_bytes/1024/1024:.2f} MB)")

    lines = []
    lines.append('"""Auto-generated by export_rf_weights.py. Do not edit by hand."""')
    lines.append("")
    lines.append(f"N_TREES = {len(rf.estimators_)}")
    lines.append(f"N_CLASSES = {n_classes}")
    lines.append(f"N_FEATURES = {n_features}")
    lines.append(f"CLASS_IDS = {list(int(c) for c in class_ids)}")
    lines.append(f"LABELS = {labels!r}")
    lines.append(f"TREE_STARTS = {tree_starts!r}")
    lines.append(f"TOTAL_NODES = {total_nodes}")
    lines.append(f'RECORD_FMT = "{record_fmt}"')
    lines.append(f"RECORD_SIZE = {record_size}")
    lines.append(f'BIN_PATH = "{BIN_OUT_PATH}"')
    lines.append("")

    with open(META_OUT_PATH, "w") as f:
        f.write("\n".join(lines))

    print(f"Wrote {META_OUT_PATH}")


if __name__ == "__main__":
    main()
