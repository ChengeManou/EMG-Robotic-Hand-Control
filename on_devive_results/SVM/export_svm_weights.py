"""
export_svm_weights.py

Exports a fitted LinearSVC's coef_/intercept_ to a pure-Python
svm_weights.py module, in the same COEF / INTERCEPT / CLASS_IDS /
LABELS format as lda_weights.py, so lda_infer.py's matmul+argmax
pattern (see svm_infer.py) can be reused verbatim for SVM.

label_map is pulled from test_windows.npz (label_map_keys/values),
same source fit_and_save_lda.py wrote it from -- there's no separate
label_map artifact from the SVM fit itself.

Usage:
    python export_svm_weights.py
"""

import joblib
import numpy as np

MODEL_PATH = "svm_model.joblib"
TEST_WINDOWS_PATH = "test_windows.npz"
OUT_PATH = "svm_weights.py"


def main():
    svm = joblib.load(MODEL_PATH)

    tw = np.load(TEST_WINDOWS_PATH, allow_pickle=True)
    label_map = dict(zip(tw["label_map_keys"].tolist(), tw["label_map_values"].tolist()))

    coef = svm.coef_            # shape (n_classes, n_features) for OvR
    intercept = svm.intercept_  # shape (n_classes,)
    class_ids = svm.classes_    # order matches rows of coef_/intercept_

    n_classes, n_features = coef.shape
    print(f"Exporting {n_classes} classes x {n_features} features")

    if n_classes != len(label_map):
        raise RuntimeError(
            f"coef_ has {n_classes} rows but label_map has {len(label_map)} "
            f"entries -- a class was dropped upstream. Check class counts "
            f"before re-fitting and re-exporting."
        )

    labels = [label_map[c] for c in class_ids]

    lines = []
    lines.append('"""Auto-generated by export_svm_weights.py. Do not edit by hand."""')
    lines.append("")
    lines.append(f"N_CLASSES = {n_classes}")
    lines.append(f"N_FEATURES = {n_features}")
    lines.append(f"CLASS_IDS = {list(int(c) for c in class_ids)}")
    lines.append(f"LABELS = {labels!r}")
    lines.append("")
    lines.append("# coef_: N_CLASSES x N_FEATURES, row order matches CLASS_IDS")
    lines.append("COEF = [")
    for row in coef:
        lines.append("    [" + ", ".join(f"{v:.10e}" for v in row) + "],")
    lines.append("]")
    lines.append("")
    lines.append("# intercept_: one per class, order matches CLASS_IDS")
    lines.append("INTERCEPT = [" + ", ".join(f"{v:.10e}" for v in intercept) + "]")
    lines.append("")

    with open(OUT_PATH, "w") as f:
        f.write("\n".join(lines))

    n_floats = n_classes * n_features + n_classes
    print(f"Wrote {OUT_PATH}: {n_floats} floats "
          f"({n_classes}x{n_features} coef + {n_classes} intercept)")


if __name__ == "__main__":
    main()