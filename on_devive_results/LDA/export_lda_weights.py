"""
export_lda_weights.py

Loads the fitted sklearn LDA model (lda_model.joblib) and flattens
its coef_ (n_classes x 16) and intercept_ (n_classes,) into a plain
MicroPython-importable .py module: lda_weights.py

For the 7-class own-arm model:
    coef_      shape (7, 16)  -> 112 floats
    intercept_ shape (7,)     ->   7 floats
    total: 119 floats (vs 68 for the earlier 4-class model)

Also writes LABELS, a {class_id: gesture_name} dict (pulled from
test_windows.npz's label_map), so the ESP32 firmware can map a
predicted integer straight to a gesture string like "index_up"
instead of a bare integer.

Copy the generated lda_weights.py to the ESP32 alongside
td_features_pure.py and lda_infer.py.
"""

import joblib
import numpy as np

MODEL_PATH = "lda_model.joblib"
TEST_WINDOWS_PATH = "test_windows.npz"
OUTPUT_PATH = "lda_weights.py"


def main():

    lda = joblib.load(MODEL_PATH)

    data = np.load(TEST_WINDOWS_PATH)
    label_map_keys = data["label_map_keys"].tolist()
    label_map_values = [str(v) for v in data["label_map_values"].tolist()]
    labels = dict(zip(label_map_keys, label_map_values))

    coef = lda.coef_.tolist()          # (n_classes, 16)
    intercept = lda.intercept_.tolist()  # (n_classes,)
    classes = lda.classes_.tolist()    # integer class ids, in coef_ row order

    n_classes = len(classes)
    n_features = len(coef[0])

    print()
    print("=" * 60)
    print("EXPORT LDA WEIGHTS")
    print("=" * 60)
    print(f"Classes  : {n_classes}")
    print(f"Features : {n_features}")
    print(f"Total floats: {n_classes * n_features + n_classes}")

    with open(OUTPUT_PATH, "w") as f:
        f.write('"""\n')
        f.write("lda_weights.py - auto-generated by export_lda_weights.py\n")
        f.write("Do not edit by hand - re-run the export script instead.\n")
        f.write('"""\n\n')

        f.write(f"N_CLASSES = {n_classes}\n")
        f.write(f"N_FEATURES = {n_features}\n\n")

        f.write("# Row order matches lda.classes_ (ascending integer label)\n")
        f.write(f"CLASS_IDS = {classes}\n\n")

        f.write("COEF = [\n")
        for row in coef:
            f.write(f"    {row},\n")
        f.write("]\n\n")

        f.write(f"INTERCEPT = {intercept}\n\n")

        f.write("# class_id -> gesture name, e.g. LABELS[CLASS_IDS[i]]\n")
        f.write(f"LABELS = {labels}\n")

    print()
    print(f"[saved] {OUTPUT_PATH}")
    print("Done.")


if __name__ == "__main__":
    main()