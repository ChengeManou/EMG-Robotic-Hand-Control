"""
export_knn_weights.py

Exports the training feature matrix (KNN's "model") as a packed binary
file + small metadata module -- same binary-not-source-literals
approach as export_test_windows.py/export_rf_weights.py, since
X_train_feat at ~3,276 x 16 floats would be unwieldy as literal source.

Writes:
    knn_train.bin   - packed float32, N_TRAIN x N_FEATURES, row-major
                       (one training sample's feature vector per row)
    knn_weights.py  - metadata: K, N_TRAIN, N_FEATURES, N_CLASSES,
                       CLASS_IDS, LABELS, Y_TRAIN (list of ints, one
                       per training sample -- small enough as a literal),
                       BIN_PATH, RECORD_SIZE

Usage:
    python export_knn_weights.py
"""

import numpy as np

TRAIN_DATA_PATH = "knn_train_data.npz"
BIN_OUT_PATH = "knn_train.bin"
META_OUT_PATH = "knn_weights.py"

K = 8  # must match fit_and_save_knn.py


def main():
    td = np.load(TRAIN_DATA_PATH, allow_pickle=True)
    X_train_feat = td["X_train_feat"]
    y_train = td["y_train"]
    label_map = dict(zip(td["label_map_keys"].tolist(), td["label_map_values"].tolist()))

    n_train, n_features = X_train_feat.shape
    class_ids = sorted(label_map.keys())
    n_classes = len(class_ids)
    labels = [label_map[c] for c in class_ids]

    print(f"Training set: {n_train} samples x {n_features} features")

    flat = X_train_feat.astype("<f4").tobytes()
    with open(BIN_OUT_PATH, "wb") as f:
        f.write(flat)

    n_bytes = len(flat)
    print(f"Wrote {BIN_OUT_PATH}: {n_bytes/1024:.1f} KB")

    lines = []
    lines.append('"""Auto-generated by export_knn_weights.py. Do not edit by hand."""')
    lines.append("")
    lines.append(f"K = {K}")
    lines.append(f"N_TRAIN = {n_train}")
    lines.append(f"N_FEATURES = {n_features}")
    lines.append(f"N_CLASSES = {n_classes}")
    lines.append(f"CLASS_IDS = {list(int(c) for c in class_ids)}")
    lines.append(f"LABELS = {labels!r}")
    lines.append(f'BIN_PATH = "{BIN_OUT_PATH}"')
    lines.append(f"RECORD_SIZE = {n_features * 4}  # bytes per training sample (float32)")
    lines.append("")
    lines.append("# One label per training sample, same row order as knn_train.bin")
    lines.append(f"Y_TRAIN = {y_train.astype(int).tolist()!r}")
    lines.append("")

    with open(META_OUT_PATH, "w") as f:
        f.write("\n".join(lines))

    meta_kb = len("\n".join(lines).encode()) / 1024
    print(f"Wrote {META_OUT_PATH} ({meta_kb:.1f} KB, mostly Y_TRAIN)")


if __name__ == "__main__":
    main()
